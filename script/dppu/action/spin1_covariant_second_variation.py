def derive_all() -> tuple[RawSpin1Hessians, RawCovariantMatrices, XYCovariantMatrices]:
    """Convenience wrapper for scripts."""
    raw = derive_raw_spin1_hessians(axis=0)
    raw_matrices = derive_raw_covariant_matrices(raw)
    xy_matrices = rotate_raw_to_xy(raw_matrices)
    return raw, raw_matrices, xy_matrices
