def _clean(expr: Any) -> Any:
    return sp.factor(sp.cancel(expr))


def _clean_matrix(matrix: Matrix) -> Matrix:
    return matrix.applyfunc(_clean)


def _sexpr(expr: Any) -> str:
    return str(_clean(expr))


def _matrix_expr(matrix: Matrix) -> str:
    return str(_clean_matrix(matrix))


def _background_c(scale: sp.Expr, r: sp.Symbol) -> MutableDenseNDimArray:
    """Return S3/T3 background structure constants in the spatial frame."""
    c_arr = MutableDenseNDimArray.zeros(DIM, DIM, DIM)
    for a in range(SPATIAL_DIM):
        for b in range(SPATIAL_DIM):
            for c in range(SPATIAL_DIM):
                eps = epsilon_3d(a, b, c)
                if eps:
                    c_arr[a, b, c] = scale * 4 * eps / r
    return c_arr


def _spin1_symbols() -> dict[str, Any]:
    omega = list(sp.symbols("omega0:3", real=True))
    delta = list(sp.symbols("delta0:3", real=True))
    d_omega = [
        [sp.symbols(f"Domega{a}{b}", real=True) for b in range(SPATIAL_DIM)]
        for a in range(SPATIAL_DIM)
    ]
    d_delta = [
        [sp.symbols(f"Ddelta{a}{b}", real=True) for b in range(SPATIAL_DIM)]
        for a in range(SPATIAL_DIM)
    ]
    dd_omega = [
        [
            [sp.symbols(f"DDomega{a}{b}{c}", real=True) for c in range(SPATIAL_DIM)]
            for b in range(SPATIAL_DIM)
        ]
        for a in range(SPATIAL_DIM)
    ]
    dd_delta = [
        [
            [sp.symbols(f"DDdelta{a}{b}{c}", real=True) for c in range(SPATIAL_DIM)]
            for b in range(SPATIAL_DIM)
        ]
        for a in range(SPATIAL_DIM)
    ]
    return {
        "omega": omega,
        "delta": delta,
        "d_omega": d_omega,
        "d_delta": d_delta,
        "dd_omega": dd_omega,
        "dd_delta": dd_delta,
        "fields": omega + delta,
        "derivatives": [item for row in d_omega + d_delta for item in row],
        "second_derivatives": [
            item
            for block in (dd_omega, dd_delta)
            for plane in block
            for row in plane
            for item in row
        ],
    }


def _linearized_spin1_structure_constants(
    *,
    r: sp.Symbol,
    L: sp.Symbol,
    curvature_scale: sp.Expr,
    symbols: dict[str, Any],
) -> MutableDenseNDimArray:
    """
    Build C^(1) from the explicit coframe deformation.

    Twist:
      e^3 -> e^3 + (L/r) omega_i e^i

    Mixing:
      e^i -> e^i + delta_i e^3,
      e^3 -> e^3 - delta_i e^i

    The derivative term is D_b lambda^a_c - D_c lambda^a_b.  The algebraic
    terms are the first-order tensor transformation of the background C.
    """
    c0 = _background_c(curvature_scale, r)
    omega = symbols["omega"]
    delta = symbols["delta"]
    d_omega = symbols["d_omega"]
    d_delta = symbols["d_delta"]

    lam = [[S.Zero for _ in range(DIM)] for _ in range(DIM)]
    for i in range(SPATIAL_DIM):
        lam[FIBER_INDEX][i] += L * omega[i] / r
        lam[i][FIBER_INDEX] += delta[i]
        lam[FIBER_INDEX][i] += -delta[i]

    def d_lam(frame_index: int, upper: int, lower: int) -> sp.Expr:
        if frame_index >= SPATIAL_DIM:
            return S.Zero
        val = S.Zero
        if upper == FIBER_INDEX and lower < SPATIAL_DIM:
            val += L * d_omega[frame_index][lower] / r
            val += -d_delta[frame_index][lower]
        if upper < SPATIAL_DIM and lower == FIBER_INDEX:
            val += d_delta[frame_index][upper]
        return val

    c1 = MutableDenseNDimArray.zeros(DIM, DIM, DIM)
    for a in range(DIM):
        for b in range(DIM):
            for c in range(DIM):
                val = S.Zero
                for d in range(DIM):
                    val += lam[a][d] * c0[d, b, c]
                    val -= lam[d][b] * c0[a, d, c]
                    val -= lam[d][c] * c0[a, b, d]
                val += d_lam(b, a, c) - d_lam(c, a, b)
                if val != S.Zero:
                    c1[a, b, c] = _clean(val)
    return c1


def _truncate_eps(expr: Any, eps: sp.Symbol, order: int = 2) -> sp.Expr:
    """Keep terms through eps**order."""
    if expr == S.Zero:
        return S.Zero
    expanded = sp.expand(expr)
    return sp.Add(*[expanded.coeff(eps, power) * eps**power for power in range(order + 1)])


def _truncate_matrix_eps(matrix: Matrix, eps: sp.Symbol, order: int = 2) -> Matrix:
    return matrix.applyfunc(lambda item: _truncate_eps(item, eps, order))


def _series_inverse_identity(matrix: Matrix, eps: sp.Symbol) -> Matrix:
    """Second-order inverse for a matrix with matrix.subs(eps, 0) == I."""
    first = matrix.applyfunc(lambda item: sp.expand(item).coeff(eps, 1))
    second = matrix.applyfunc(lambda item: sp.expand(item).coeff(eps, 2))
    return _truncate_matrix_eps(
        sp.eye(DIM) - eps * first + eps**2 * (first * first - second),
        eps,
    )


def _coframe_matrices(
    *,
    r: sp.Symbol,
    L: sp.Symbol,
    eps: sp.Symbol,
    symbols: dict[str, Any],
    include_quadratic_cosine: bool = False,
    phase5a_inverse_order: bool = True,
) -> tuple[Matrix, Matrix, Matrix]:
    """
    Build the old-DPPU coframe transform and inverse to O(eps^2).

    The transform follows the same old-index order as S3Geometry before the
    LZ adapter: old spatial indices are 0,1,2 and old fiber/time is 3.  The
    default is the Phase5A canonical cd/sd polynomial extraction convention:
    the sd_i leg is varied while cd_i is held as an independent background
    symbol at cd_i=1.  Setting include_quadratic_cosine=True restores the
    exact SO(4) small-angle cosine c_i=1-eps**2*delta_i**2/2 for diagnostics.

    S3Geometry applies the rotation tensor transform with Mi[e,b]=M[e,b].
    phase5a_inverse_order=True keeps that index ordering.  False is an
    ordinary-inverse diagnostic, but completion comparisons keep True so the
    first-order Phase5A branch is fixed and only the second-order completion
    changes.
    """
    omega = symbols["omega"]
    delta = symbols["delta"]
    twist = sp.eye(DIM)
    for i in range(SPATIAL_DIM):
        twist[FIBER_INDEX, i] += eps * L * omega[i] / r

    rotation = sp.eye(DIM)
    for i in range(SPATIAL_DIM):
        c_i = (
            S.One - eps**2 * delta[i] ** 2 / 2
            if include_quadratic_cosine
            else S.One
        )
        s_i = eps * delta[i]
        rot_i = sp.eye(DIM)
        rot_i[i, i] = c_i
        rot_i[FIBER_INDEX, FIBER_INDEX] = c_i
        rot_i[i, FIBER_INDEX] = s_i
        rot_i[FIBER_INDEX, i] = -s_i
        rotation = _truncate_matrix_eps(rotation * rot_i, eps)

    transform = _truncate_matrix_eps(rotation * twist, eps)
    twist_inv = sp.eye(DIM)
    for i in range(SPATIAL_DIM):
        twist_inv[FIBER_INDEX, i] += -eps * L * omega[i] / r
    rotation_inverse_for_indices = rotation if phase5a_inverse_order else rotation.T
    inverse = _truncate_matrix_eps(twist_inv * rotation_inverse_for_indices, eps)
    return transform, inverse, rotation


def _differentiate_old_frame(
    frame_index: int,
    expr: sp.Expr,
    symbols: dict[str, Any],
) -> sp.Expr:
    """Symbolic derivative along the old spatial frame index."""
    if frame_index >= SPATIAL_DIM or expr == S.Zero:
        return S.Zero

    d_map = symbols.get("_derivative_map")
    if d_map is None:
        d_map = {}
        for p in range(SPATIAL_DIM):
            for i in range(SPATIAL_DIM):
                d_map[(p, symbols["omega"][i])] = symbols["d_omega"][p][i]
                d_map[(p, symbols["delta"][i])] = symbols["d_delta"][p][i]
                for q in range(SPATIAL_DIM):
                    d_map[(p, symbols["d_omega"][q][i])] = symbols["dd_omega"][p][q][i]
                    d_map[(p, symbols["d_delta"][q][i])] = symbols["dd_delta"][p][q][i]
        symbols["_derivative_map"] = d_map

    val = S.Zero
    for sym in list(expr.free_symbols):
        key = (frame_index, sym)
        if key in d_map:
            val += sp.diff(expr, sym) * d_map[key]
    return sp.expand(val)


def _coframe_structure_constants_lz(
    *,
    r: sp.Symbol,
    L: sp.Symbol,
    curvature_scale: sp.Expr,
    eps: sp.Symbol,
    symbols: dict[str, Any],
    include_quadratic_cosine: bool = False,
    phase5a_inverse_order: bool = True,
) -> tuple[MutableDenseNDimArray, Matrix, Matrix]:
    """Return full old->LZ remapped C(eps) including frame-derivative terms."""
    c0_old = _background_c(curvature_scale, r)
    transform, inverse, rotation = _coframe_matrices(
        r=r,
        L=L,
        eps=eps,
        symbols=symbols,
        include_quadratic_cosine=include_quadratic_cosine,
        phase5a_inverse_order=phase5a_inverse_order,
    )
    nonzero_c0 = [
        (a, b, c, c0_old[a, b, c])
        for a in range(DIM)
        for b in range(DIM)
        for c in range(DIM)
        if c0_old[a, b, c] != S.Zero
    ]
    c_old = MutableDenseNDimArray.zeros(DIM, DIM, DIM)
    for a in range(DIM):
        for b in range(DIM):
            for c in range(DIM):
                val = S.Zero
                for d, e, f, old_value in nonzero_c0:
                    val += transform[a, d] * inverse[e, b] * inverse[f, c] * old_value
                for h in range(DIM):
                    for e in range(SPATIAL_DIM):
                        val += (
                            -transform[a, h]
                            * inverse[e, b]
                            * _differentiate_old_frame(e, inverse[h, c], symbols)
                        )
                        val += (
                            transform[a, h]
                            * inverse[e, c]
                            * _differentiate_old_frame(e, inverse[h, b], symbols)
                        )
                val = _truncate_eps(val, eps)
                if val != S.Zero:
                    c_old[a, b, c] = val

    c_lz = MutableDenseNDimArray.zeros(DIM, DIM, DIM)
    for a in range(DIM):
        for b in range(DIM):
            for c in range(DIM):
                val = c_old[a, b, c]
                if val != S.Zero:
                    c_lz[
                        old_to_lz_index(a),
                        old_to_lz_index(b),
                        old_to_lz_index(c),
                    ] = val
    return c_lz, inverse, transform


def _coefficient_array(
    arr: MutableDenseNDimArray,
    eps: sp.Symbol,
    power: int,
) -> MutableDenseNDimArray:
    out = MutableDenseNDimArray.zeros(*arr.shape)
    for a in range(DIM):
        for b in range(DIM):
            for c in range(DIM):
                val = arr[a, b, c]
                if val != S.Zero:
                    coeff = sp.expand(val).coeff(eps, power)
                    if coeff != S.Zero:
                        out[a, b, c] = coeff
    return out


def _complete_ricci_l2_expression(
    *,
    r: sp.Symbol,
    L: sp.Symbol,
    curvature_scale: sp.Expr,
    symbols: dict[str, Any],
    include_quadratic_cosine: bool = False,
    phase5a_inverse_order: bool = True,
) -> dict[str, Any]:
    """
    Compute the O(eps^2) Ricci scalar using complete frame Riemann terms.

    The background check explicitly calls compute_riemann_tensor and
    compute_ricci_scalar.  The O(eps^2) coefficient is then assembled from the
    same frame-Riemann formula by perturbative bookkeeping; this avoids the
    expensive full-tensor cancel() path while retaining all terms:
    e(Gamma2), e1(Gamma1), Gamma0*Gamma2, Gamma1*Gamma1, Gamma*C.
    """
    eps = sp.Symbol("eps", real=True)
    c_full, inverse_old, transform_old = _coframe_structure_constants_lz(
        r=r,
        L=L,
        curvature_scale=curvature_scale,
        eps=eps,
        symbols=symbols,
        include_quadratic_cosine=include_quadratic_cosine,
        phase5a_inverse_order=phase5a_inverse_order,
    )
    c0 = _coefficient_array(c_full, eps, 0)
    c1 = _coefficient_array(c_full, eps, 1)
    c2 = _coefficient_array(c_full, eps, 2)
    gamma0 = compute_christoffel_frame(
        c0,
        DIM,
        metric=LORENTZ_METRIC,
        metric_inv=LORENTZ_METRIC,
    )
    gamma1 = compute_christoffel_frame(
        c1,
        DIM,
        metric=LORENTZ_METRIC,
        metric_inv=LORENTZ_METRIC,
    )
    gamma2 = compute_christoffel_frame(
        c2,
        DIM,
        metric=LORENTZ_METRIC,
        metric_inv=LORENTZ_METRIC,
    )

    riemann0 = compute_riemann_tensor(gamma0, c0, DIM)
    ricci0 = _clean(compute_ricci_scalar(riemann0, DIM, metric_inv=LORENTZ_METRIC))

    inverse1_old = [
        [sp.expand(inverse_old[e, c]).coeff(eps, 1) for c in range(DIM)]
        for e in range(DIM)
    ]

    def d0_lz(lz_index: int, expr: sp.Expr) -> sp.Expr:
        old_index = lz_to_old_index(lz_index)
        if old_index >= SPATIAL_DIM:
            return S.Zero
        return _differentiate_old_frame(old_index, expr, symbols)

    def d1_lz(lz_index: int, expr: sp.Expr) -> sp.Expr:
        old_index = lz_to_old_index(lz_index)
        val = S.Zero
        for e in range(SPATIAL_DIM):
            val += inverse1_old[e][old_index] * _differentiate_old_frame(e, expr, symbols)
        return sp.expand(val)

    ricci_l1 = S.Zero
    ricci_l2 = S.Zero
    for b in range(DIM):
        for d in range(DIM):
            if LORENTZ_METRIC[b, d] == S.Zero:
                continue
            ricci_bd_l1 = S.Zero
            ricci_bd = S.Zero
            for a in range(DIM):
                c = a
                term_l1 = (
                    d0_lz(c, gamma1[a, b, d])
                    - d0_lz(d, gamma1[a, b, c])
                )
                term = (
                    d0_lz(c, gamma2[a, b, d])
                    - d0_lz(d, gamma2[a, b, c])
                    + d1_lz(c, gamma1[a, b, d])
                    - d1_lz(d, gamma1[a, b, c])
                )
                for e in range(DIM):
                    term_l1 += (
                        gamma0[a, e, c] * gamma1[e, b, d]
                        + gamma1[a, e, c] * gamma0[e, b, d]
                    )
                    term_l1 -= (
                        gamma0[a, e, d] * gamma1[e, b, c]
                        + gamma1[a, e, d] * gamma0[e, b, c]
                    )
                    term_l1 += (
                        gamma0[a, b, e] * c1[e, c, d]
                        + gamma1[a, b, e] * c0[e, c, d]
                    )
                    term += (
                        gamma0[a, e, c] * gamma2[e, b, d]
                        + gamma1[a, e, c] * gamma1[e, b, d]
                        + gamma2[a, e, c] * gamma0[e, b, d]
                    )
                    term -= (
                        gamma0[a, e, d] * gamma2[e, b, c]
                        + gamma1[a, e, d] * gamma1[e, b, c]
                        + gamma2[a, e, d] * gamma0[e, b, c]
                    )
                    term += (
                        gamma0[a, b, e] * c2[e, c, d]
                        + gamma1[a, b, e] * c1[e, c, d]
                        + gamma2[a, b, e] * c0[e, c, d]
                    )
                ricci_bd_l1 += term_l1
                ricci_bd += term
            ricci_l1 += LORENTZ_METRIC[b, d] * ricci_bd_l1
            ricci_l2 += LORENTZ_METRIC[b, d] * ricci_bd

    det_l1 = sp.expand(transform_old.det()).coeff(eps, 1)
    det_l2 = sp.expand(transform_old.det()).coeff(eps, 2)
    return {
        "ricci0": ricci0,
        "ricci_l1": sp.expand(ricci_l1),
        "ricci_l2": sp.expand(ricci_l2),
        "det_l1": _clean(det_l1),
        "det_l2": _clean(det_l2),
    }


def _complete_ricci_l2_full_tensor_coefficient(
    *,
    r: sp.Symbol,
    L: sp.Symbol,
    curvature_scale: sp.Expr,
    symbols: dict[str, Any],
    include_quadratic_cosine: bool = False,
    phase5a_inverse_order: bool = True,
) -> sp.Expr:
    """Compute the eps**2 Ricci scalar coefficient by the full dppu tensor path."""
    eps = sp.Symbol("eps", real=True)
    c_full, inverse_old, _ = _coframe_structure_constants_lz(
        r=r,
        L=L,
        curvature_scale=curvature_scale,
        eps=eps,
        symbols=symbols,
        include_quadratic_cosine=include_quadratic_cosine,
        phase5a_inverse_order=phase5a_inverse_order,
    )
    gamma_full = compute_christoffel_frame(
        c_full,
        DIM,
        metric=LORENTZ_METRIC,
        metric_inv=LORENTZ_METRIC,
    )

    def frame_deriv_lz(lz_index: int, expr: sp.Expr) -> sp.Expr:
        old_index = lz_to_old_index(lz_index)
        val = S.Zero
        for e in range(SPATIAL_DIM):
            val += inverse_old[e, old_index] * _differentiate_old_frame(e, expr, symbols)
        return _truncate_eps(sp.expand(val), eps)

    riemann_full = compute_riemann_tensor(
        gamma_full,
        c_full,
        DIM,
        frame_deriv=frame_deriv_lz,
    )
    ricci_full = compute_ricci_scalar(
        riemann_full,
        DIM,
        metric_inv=LORENTZ_METRIC,
    )
    return sp.expand(ricci_full).coeff(eps, 2)


def _select_terms(
    expr: sp.Expr,
    *,
    derivative_symbols: list[sp.Symbol],
    field_symbols: list[sp.Symbol],
    mode: str,
) -> sp.Expr:
    terms: list[sp.Expr] = []
    derivative_set = set(derivative_symbols)
    field_set = set(field_symbols)
    for term in sp.Add.make_args(sp.expand(expr)):
        free = term.free_symbols
        has_derivative = bool(free & derivative_set)
        has_field = bool(free & field_set)
        if mode == "pure_derivative" and has_derivative and not has_field:
            terms.append(term)
        elif mode == "field_mass" and has_field and not has_derivative:
            terms.append(term)
        elif mode == "first_derivative" and has_field and has_derivative:
            terms.append(term)
    return _clean(sp.Add(*terms)) if terms else S.Zero


def _curl_components(d_var: list[list[sp.Symbol]]) -> list[sp.Expr]:
    return [
        sum(
            epsilon_3d(i, j, k) * d_var[j][k]
            for j in range(SPATIAL_DIM)
            for k in range(SPATIAL_DIM)
        )
        for i in range(SPATIAL_DIM)
    ]


def _theta(d_var: list[list[sp.Symbol]]) -> sp.Expr:
    return sum(d_var[i][i] for i in range(SPATIAL_DIM))


def _shear_matrix(d_var: list[list[sp.Symbol]]) -> Matrix:
    theta = _theta(d_var)
    return Matrix(
        SPATIAL_DIM,
        SPATIAL_DIM,
        lambda i, j: (d_var[i][j] + d_var[j][i]) / 2
        - (S.One if i == j else S.Zero) * theta / 3,
    )


def _gradient_invariant(
    d_left: list[list[sp.Symbol]],
    d_right: list[list[sp.Symbol]],
    kind: str,
) -> sp.Expr:
    if kind == "theta":
        return _theta(d_left) * _theta(d_right)
    if kind == "curl":
        c_left = _curl_components(d_left)
        c_right = _curl_components(d_right)
        return sum(c_left[i] * c_right[i] for i in range(SPATIAL_DIM))
    if kind == "shear":
        s_left = _shear_matrix(d_left)
        s_right = _shear_matrix(d_right)
        return sum(
            s_left[i, j] * s_right[i, j]
            for i in range(SPATIAL_DIM)
            for j in range(SPATIAL_DIM)
        )
    raise ValueError(f"unknown invariant kind: {kind}")


def _fit_gradient_matrices(
    derivative_expr: sp.Expr,
    symbols: dict[str, Any],
) -> tuple[Matrix, Matrix, Matrix]:
    """Fit the derivative expression to theta/curl/shear raw matrices."""
    d_vars = [symbols["d_omega"], symbols["d_delta"]]
    unknowns = {
        kind: Matrix(
            [
                [sp.symbols(f"g_{kind}_00"), sp.symbols(f"g_{kind}_01")],
                [sp.symbols(f"g_{kind}_01"), sp.symbols(f"g_{kind}_11")],
            ]
        )
        for kind in ("theta", "curl", "shear")
    }
    model = S.Zero
    for kind, matrix in unknowns.items():
        for a in range(2):
            for b in range(a, 2):
                factor = S.One if a == b else S(2)
                model += factor * matrix[a, b] * _gradient_invariant(
                    d_vars[a], d_vars[b], kind
                )
    variables = symbols["derivatives"]
    equations = sp.Poly(sp.expand(derivative_expr - model), variables).coeffs()
    solve_vars = [
        unknowns[kind][i, j]
        for kind in ("theta", "curl", "shear")
        for i, j in ((0, 0), (0, 1), (1, 1))
    ]
    solution = sp.solve(equations, solve_vars, dict=True)
    if not solution:
        raise ValueError("could not fit derivative expression to spin-1 gradient basis")
    sol = solution[0]

    def mat(kind: str) -> Matrix:
        return _clean_matrix(
            Matrix(
                [
                    [sol[unknowns[kind][0, 0]], sol[unknowns[kind][0, 1]]],
                    [sol[unknowns[kind][0, 1]], sol[unknowns[kind][1, 1]]],
                ]
            )
        )

    return mat("theta"), mat("curl"), mat("shear")


def _fit_mass_matrix(mass_expr: sp.Expr, symbols: dict[str, Any]) -> Matrix:
    omega = symbols["omega"]
    delta = symbols["delta"]
    m00, m01, m11 = sp.symbols("m00 m01 m11")
    model = sum(
        m00 * omega[i] ** 2 + 2 * m01 * omega[i] * delta[i] + m11 * delta[i] ** 2
        for i in range(SPATIAL_DIM)
    )
    variables = symbols["fields"]
    equations = sp.Poly(sp.expand(mass_expr - model), variables).coeffs()
    solution = sp.solve(equations, [m00, m01, m11], dict=True)
    if not solution:
        raise ValueError("could not fit mass expression to raw spin-1 matrix")
    sol = solution[0]
    return _clean_matrix(Matrix([[sol[m00], sol[m01]], [sol[m01], sol[m11]]]))


def _d_symbol(symbols: dict[str, Any], kind: str, frame: int, component: int) -> sp.Symbol:
    if kind == "omega":
        return symbols["d_omega"][frame][component]
    if kind == "delta":
        return symbols["d_delta"][frame][component]
    raise ValueError(f"unknown field kind: {kind}")


def _reduce_second_derivatives_by_parts(
    expr: sp.Expr,
    symbols: dict[str, Any],
) -> tuple[sp.Expr, list[dict[str, str]]]:
    """Reduce field*D_iD_j(field) terms by one symbolic integration by parts."""
    fields = symbols["omega"] + symbols["delta"]
    second_info: dict[sp.Symbol, tuple[str, int, int, int]] = {}
    for p in range(SPATIAL_DIM):
        for q in range(SPATIAL_DIM):
            for i in range(SPATIAL_DIM):
                second_info[symbols["dd_omega"][p][q][i]] = ("omega", p, q, i)
                second_info[symbols["dd_delta"][p][q][i]] = ("delta", p, q, i)

    reduced = S.Zero
    rows: list[dict[str, str]] = []
    for term in sp.Add.make_args(sp.expand(expr)):
        hits = [sym for sym in second_info if sym in term.free_symbols]
        if len(hits) != 1:
            reduced += term
            continue
        dd_sym = hits[0]
        kind, p, q, i = second_info[dd_sym]
        coeff = term / dd_sym
        field_hits = [field for field in fields if field in coeff.free_symbols]
        if len(field_hits) != 1:
            reduced += term
            continue
        field = field_hits[0]
        coeff_no_field = coeff / field
        left_kind = "omega" if field in symbols["omega"] else "delta"
        left_i = (
            symbols["omega"].index(field)
            if left_kind == "omega"
            else symbols["delta"].index(field)
        )
        replacement = -coeff_no_field * _d_symbol(symbols, left_kind, p, left_i) * _d_symbol(
            symbols, kind, q, i
        )
        reduced += replacement
        rows.append(
            {
                "trace_id": f"IBP-{len(rows) + 1:02d}",
                "stage": "second_derivative_reduction",
                "expression": _sexpr(term),
                "result": _sexpr(replacement),
                "provenance_status": "RULE_APPLIED_SYMBOLICALLY",
            }
        )
    return sp.expand(reduced), rows


def _canonicalize_first_derivative_ibp(expr: sp.Expr, symbols: dict[str, Any]) -> sp.Expr:
    """
    Canonicalize same-field U_i D_a U_j terms up to a boundary term.

    This lets the parity-odd same-field channel fit U.curl(U) rather than
    retaining duplicate integration-by-parts representatives.
    """
    d_info: dict[sp.Symbol, tuple[str, int, int]] = {}
    f_info: dict[sp.Symbol, tuple[str, int]] = {}
    for p in range(SPATIAL_DIM):
        for i in range(SPATIAL_DIM):
            d_info[symbols["d_omega"][p][i]] = ("omega", p, i)
            d_info[symbols["d_delta"][p][i]] = ("delta", p, i)
            f_info[symbols["omega"][i]] = ("omega", i)
            f_info[symbols["delta"][i]] = ("delta", i)

    out = S.Zero
    for term in sp.Add.make_args(sp.expand(expr)):
        d_hits = [sym for sym in d_info if sym in term.free_symbols]
        f_hits = [sym for sym in f_info if sym in term.free_symbols]
        if len(d_hits) == 1 and len(f_hits) == 1:
            d_sym = d_hits[0]
            f_sym = f_hits[0]
            d_kind, frame, d_component = d_info[d_sym]
            f_kind, f_component = f_info[f_sym]
            coeff = term / (d_sym * f_sym)
            if d_kind == f_kind and d_component > f_component:
                out += (
                    -coeff
                    * _d_symbol(symbols, d_kind, frame, f_component)
                    * (symbols["omega"][d_component] if d_kind == "omega" else symbols["delta"][d_component])
                )
                continue
        out += term
    return sp.expand(out)


def _parity_odd_operator_expr(
    left_fields: list[sp.Symbol],
    right_derivatives: list[list[sp.Symbol]],
) -> sp.Expr:
    curl = _curl_components(right_derivatives)
    return sum(left_fields[i] * curl[i] for i in range(SPATIAL_DIM))


def _fit_parity_odd_matrix(first_derivative_expr: sp.Expr, symbols: dict[str, Any]) -> Matrix:
    """Fit parity-odd first-derivative terms to U_A.curl(U_B)."""
    p00, p01, p10, p11 = sp.symbols("p_odd_00 p_odd_01 p_odd_10 p_odd_11")
    ops = [
        _parity_odd_operator_expr(symbols["omega"], symbols["d_omega"]),
        _parity_odd_operator_expr(symbols["omega"], symbols["d_delta"]),
        _parity_odd_operator_expr(symbols["delta"], symbols["d_omega"]),
        _parity_odd_operator_expr(symbols["delta"], symbols["d_delta"]),
    ]
    model = p00 * ops[0] + p01 * ops[1] + p10 * ops[2] + p11 * ops[3]
    variables = symbols["fields"] + symbols["derivatives"]
    expr_canonical = _canonicalize_first_derivative_ibp(first_derivative_expr, symbols)
    model_canonical = _canonicalize_first_derivative_ibp(model, symbols)
    equations = sp.Poly(sp.expand(expr_canonical - model_canonical), variables).coeffs()
    solution = sp.solve(equations, [p00, p01, p10, p11], dict=True)
    if not solution:
        raise ValueError("could not fit first-derivative expression to parity-odd basis")
    sol = solution[0]
    return _clean_matrix(Matrix([[sol[p00], sol[p01]], [sol[p10], sol[p11]]]))


