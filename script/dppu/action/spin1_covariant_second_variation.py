"""
Spin-1 Complete Second-Variation Diagnostics
============================================

Local symbolic module for Phase5B-6G-v.

The spatial block is computed from a complete frame Riemann/Ricci
second-variation route in the DPPU-LZ Lorentzian convention:

  coframe deformation -> C^(0,1,2) -> Gamma^(0,1,2) -> Ricci scalar O(eps^2)

This intentionally keeps the inhomogeneous result independent from the
homogeneous velocity Hessian.  The zero-gradient output is converted to the
Phase5A frozen cd/sd polynomial convention before coefficients are published.
The ADM shift block is generated by expanding the K_ij square with the same
velocity Gram matrix, then extracting the dot/shift coefficients.
"""

