def in_span(basis: list[sp.Matrix], target: sp.Matrix) -> bool:
    if not basis:
        return target == sp.zeros(target.rows, 1)
    matrix = sp.Matrix.hstack(*basis)
    return int(matrix.rank()) == int(matrix.row_join(target).rank())


def kernel_basis(topology: str) -> list[sp.Matrix]:
    """Zero-mode tangent space = ker(n), generated from the engine n-matrix."""
    return list(topology_n_data(topology)["n_matrix"].nullspace())


def basis_audit_row(topology: str) -> dict[str, str]:
    n_data = topology_n_data(topology)
    n_matrix = n_data["n_matrix"]
    kernel = kernel_basis(topology)
    d_zero = int(n_data["d_zero"])
    nullity_ok = len(kernel) == d_zero
    return {
        "topology": topology,
        "n_matrix": mat_str(n_matrix),
        "ker_n_nullity": str(len(kernel)),
        "d_zero": str(d_zero),
        "ker_n_nullity_matches_d_zero": "true" if nullity_ok else "false",
        "basis_source": "zero-mode tangent space = ker(n) generated by topology_n_data(n_matrix).nullspace(); no hand-listed basis; tangent membership tested against this kernel",
        "status": "PASS" if nullity_ok else "FAIL",
    }


def classification_from_coeffs(coeffs: dict[str, str]) -> str:
    nonzero = [key for key in ("1", "2", "3", "4") if sp.sympify(coeffs[key]) != 0]
    return "EXACT_FLAT_MODULUS" if not nonzero else "WALL"


def evaluate_original_path(topology: str, label: str) -> dict[str, Any] | None:
    path_by_label = {
        "T3_e1": "t3_shape",
        "T3_e2": "t3_shape",
        "T3_e3": "t3_shape",
        "nil3_betaminus": "nil3_betaminus",
        "nil3_betaplus_u": "nil3_betaplus_u",
        "sol3_betax": "sol3_betax",
    }
    path = path_by_label.get(label)
    if path is None:
        return None
    return palatini_symbolic_series(topology, path, route="T")


def evaluate_direction(topology: str, label: str, vector: list[sp.Expr]) -> dict[str, str]:
    original = evaluate_original_path(topology, label)
    if original is not None and original.get("status") == "PASS":
        coeffs = original["coefficients"]
        classification = classification_from_coeffs(coeffs)
        engine_source = f"palatini_symbolic_series:{original.get('path', 'named_path')}"
    elif topology == "T3":
        coeffs = {"1": "nan", "2": "nan", "3": "nan", "4": "nan"}
        classification = "ENGINE_PATH_FAILED"
        engine_source = "palatini_symbolic_series_required_no_fallback"
    else:
        potential = palatini_reduced_density(topology, vector)
        result = classify_finite_direction(potential, vector)
        coeffs = result["coefficients"]
        classification = result["classification"]
        engine_source = "paper07_palatini_reduced_density"

    basis_row = basis_audit_row(topology)
    tangent_in_ker = in_span(kernel_basis(topology), sp.Matrix(vector))
    # Central-theorem cross-check: a flat modulus must lie in ker(n); a wall
    # must be transverse to it (n . v != 0). Classification (palatini series)
    # and kernel membership (engine n-matrix) are computed independently, so
    # their agreement is a genuine check, not a tautology.
    if classification == "EXACT_FLAT_MODULUS":
        modulus_kernel_consistent = tangent_in_ker
    elif classification == "WALL":
        modulus_kernel_consistent = not tangent_in_ker
    else:
        modulus_kernel_consistent = False

    status = "FAIL"
    if topology == "T3" or label == "nil3_betaminus":
        status = "PASS" if classification == "EXACT_FLAT_MODULUS" and modulus_kernel_consistent else "FAIL"
    elif label in {"nil3_betaplus_u", "sol3_betax"}:
        linear = sp.sympify(coeffs["1"])
        status = "PASS" if classification == "WALL" and linear != 0 and modulus_kernel_consistent else "FAIL"
    return {
        "topology": topology,
        "label": label,
        "vector": str(vector),
        "classification": classification,
        "linear_coeff": coeffs["1"],
        "quadratic_coeff": coeffs["2"],
        "tangent_in_ker_n": "true" if tangent_in_ker else "false",
        "ker_n_nullity": basis_row["ker_n_nullity"],
        "ker_n_nullity_matches_d_zero": basis_row["ker_n_nullity_matches_d_zero"],
        "modulus_kernel_consistent": "true" if modulus_kernel_consistent else "false",
        "engine_source": engine_source,
        "status": status,
    }


def t3_engine_first_ok(rows: list[dict[str, str]]) -> bool:
    t3_rows = [row for row in rows if row["topology"] == "T3"]
    return bool(t3_rows) and all(
        row["engine_source"].startswith("palatini_symbolic_series:")
        and row["classification"] == "EXACT_FLAT_MODULUS"
        for row in t3_rows
    )


def dewitt_trace_free_positive() -> bool:
    metric = minisuperspace_dewitt_metric()
    directions = [
        sp.Matrix([1, -1, 0]),
        sp.Matrix([1, 0, -1]),
        sp.Matrix([1, 1, -2]),
    ]
    for direction in directions:
        trace = simplify_expr(sum(direction))
        norm = vector_norm(metric, direction)
        if trace != 0 or sp.simplify(norm) <= 0:
            return False
    return True


